"""Write web/assets/manifest.js: the stage and the shared skill effects.

Fighters are not in here: each one lives in web/characters/<id>/character.js.
"""
import json
import os

A = "web/assets"
VFX = ["bird", "naga", "chakra", "tiger", "rocks", "yama", "storm",
       "crack", "fists", "blades", "buffalo", "groundfire", "guard",
       "magnet", "ramasun", "wind", "sunfire", "icespear", "blink", "blinkrift",
       "claw", "clawheavy", "clawx", "tigerclaw", "tigerbeast", "jungleaura", "leaves", "bullet", "pistol",
       "goldbolt", "goldburst", "bluebolt", "goldbeam", "fireblast", "thunderball", "whirl", "rocket", "talai", "rocketride", "bigride", "taphotwave", "spiritwave", "bloodslash", "spiritshield", "spiritguard", "whiteimpact", "bloodring", "soulicon", "bloodicon", "yanttiger", "yantface", "yantroar", "krawpetch", "yantblack"]
# animated effect sheets from tools/fetch_vfx.py: key -> (fps, loop)
VFX_ANIM = {"bird": (16, True), "naga": (18, True), "tiger": (18, True),
            "rocks": (0, False), "yama": (0, False), "storm": (16, True),
            "buffalo": (18, True), "groundfire": (14, True), "fists": (24, True),
            "magnet": (16, True), "ramasun": (0, False), "sunfire": (12, True),
            "tigerbeast": (14, True), "jungleaura": (12, True)}

vfx_anim = {}
for key, (fps, loop) in VFX_ANIM.items():
    meta = f"web/assets/vfx_{key}_anim.json"
    if os.path.exists(meta):
        info = json.load(open(meta))
        vfx_anim[key] = {"image": f"assets/vfx_{key}_anim.png", "fps": fps, "loop": loop, **info}

manifest = {
    "worldWidth": 2600,
    "groundY": 306,
    "background": "assets/bg_village.png",
    # one of these is picked at random for every match
    "backgrounds": [f"assets/{n}" for n in sorted(os.listdir(A)) if n.startswith("bg_") and n.endswith(".png")],
    # stages with readable signs: tile them straight, never mirrored
    "bgNoMirror": ["assets/bg_alley.png"],
    "vfx": {**{k: f"assets/vfx_{k}.png" for k in VFX},
            # per-skill icons from tools/make_icons.py: ic_<character>_<skill>
            **{"ic_" + n[:-4]: f"assets/icons/{n}" for n in sorted(os.listdir(f"{A}/icons")) if n.endswith(".png")}},
    "vfxAnim": vfx_anim,
    # menu music (web/music.js): every audio file in assets/music, played in random order
    "music": [f"assets/music/{n}" for n in sorted(os.listdir(f"{A}/music")) if n.lower().endswith((".mp3", ".m4a", ".ogg", ".aac"))]
             if os.path.isdir(f"{A}/music") else [],
    # fight music from tools/compose_music.py
    "fightMusic": [f"assets/fightmusic/{n}" for n in sorted(os.listdir(f"{A}/fightmusic")) if n.endswith(".mp3")]
                  if os.path.isdir(f"{A}/fightmusic") else [],
}
with open(f"{A}/manifest.js", "w") as f:
    f.write("// Generated by tools/build_manifest.py\nwindow.MANIFEST = " + json.dumps(manifest, indent=1) + ";\n")
print("ok", sorted(manifest))
